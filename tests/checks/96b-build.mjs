// Plan 9 / SPLIT — the built file is generated from src/ by tools/build.mjs and must never drift from it. This check needs no page:
// (1) `node tools/build.mjs --check` exits 0 on the committed tree; (2) after a one-byte change to a part it exits 1 and names the drift
// (the part is restored byte-for-byte in a finally); (3) every source part is CRLF-only with zero raw control bytes, and the generated
// PRICES block lives in src/js/02-prices.js (the file tests/tools/sync-prices.mjs targets), whose markers reach the built file unchanged.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const ROOT = path.join(import.meta.dirname, '..', '..');
const BUILD = path.join(ROOT, 'tools', 'build.mjs');
const PRICES_PART = path.join(ROOT, 'src', 'js', '02-prices.js');
const BUILT = path.join(ROOT, 'AI Usage Dashboard.html');

const buildCheck = () => spawnSync(process.execPath, [BUILD, '--check'], { cwd: ROOT, encoding: 'utf8' });
const tail = (r) => String((r.stdout || '') + (r.stderr || '') + (r.error ? r.error.message : '')).trim().slice(0, 300);

function sourceFiles() {
  const out = [];
  const walk = (dir) => { for (const e of fs.readdirSync(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); if (e.isDirectory()) walk(p); else out.push(p); } };
  walk(path.join(ROOT, 'src'));
  return out;
}

function lineEndingFaults(buf) {
  let bareLf = 0, control = 0;
  for (let i = 0; i < buf.length; i++) {
    if (buf[i] === 10 && (i === 0 || buf[i - 1] !== 13)) bareLf++;
    if (buf[i] < 9) control++;
  }
  return { bareLf, control, endsCrlf: buf.length >= 2 && buf[buf.length - 2] === 13 && buf[buf.length - 1] === 10 };
}

export async function run({ ok }) {
  const clean = buildCheck();
  ok('build: node tools/build.mjs --check exits 0 on the committed tree (AI Usage Dashboard.html == build of src/)', clean.status === 0, tail(clean));

  const original = fs.readFileSync(PRICES_PART);
  let drifted, restored;
  try {
    fs.writeFileSync(PRICES_PART, Buffer.concat([original.subarray(0, original.length - 2), Buffer.from(' \r\n')]));   // one byte before the final CRLF
    drifted = buildCheck();
  } finally {
    fs.writeFileSync(PRICES_PART, original);
    restored = fs.readFileSync(PRICES_PART).equals(original);
  }
  ok('build: --check exits 1 and reports DRIFT after a one-byte change to a part (part restored byte-for-byte afterwards)',
    drifted.status === 1 && /DRIFT/.test(tail(drifted)) && restored, JSON.stringify({ status: drifted.status, out: tail(drifted), restored }));
  ok('build: --check does not touch the built file (the drift run leaves AI Usage Dashboard.html == build of the restored src/)', buildCheck().status === 0, '');

  const faults = sourceFiles().map(p => ({ p: path.relative(ROOT, p), ...lineEndingFaults(fs.readFileSync(p)) })).filter(f => f.bareLf || f.control || !f.endsCrlf);
  ok('hygiene: every file under src/ is CRLF-only, ends with CRLF and has no raw control bytes (<0x09)', faults.length === 0, JSON.stringify(faults));

  const BEGIN = '/* PRICES:BEGIN (generated by tests/tools/sync-prices.mjs — edit the JSON, not this block) */';
  const part = fs.readFileSync(PRICES_PART, 'utf8'), built = fs.readFileSync(BUILT, 'utf8');
  const block = (s) => { const b = s.indexOf(BEGIN), e = s.indexOf('/* PRICES:END */', b); return b >= 0 && e > b ? s.slice(b, e) : null; };
  ok('prices: the generated PRICES block lives in src/js/02-prices.js and reaches the built file unchanged (sync-prices targets the part, the build carries it)',
    block(part) !== null && block(part) === block(built), JSON.stringify({ inPart: block(part) !== null, inBuilt: block(built) !== null, same: block(part) === block(built) }));
  const sync = spawnSync(process.execPath, [path.join(ROOT, 'tests', 'tools', 'sync-prices.mjs'), '--check'], { cwd: ROOT, encoding: 'utf8' });
  ok('prices: node tests/tools/sync-prices.mjs --check exits 0 against the part', sync.status === 0, tail(sync));
}
