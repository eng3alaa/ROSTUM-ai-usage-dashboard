// Plan 9 — render the verified price rows (docs/superpowers/specs/2026-10-15-price-rows.json) into the dashboard's PRICES block.
// Since the SPLIT the block lives in src/js/02-prices.js (the part tools/build.mjs concatenates into AI Usage Dashboard.html).
//
//   node tests/tools/sync-prices.mjs            rewrite the block between the PRICES:BEGIN / PRICES:END markers in the part (creates them
//                                               around the old DEFAULT_PRICES on the first run), then run the build so the built file
//                                               follows; the part's line endings (CRLF) are preserved
//   node tests/tools/sync-prices.mjs --check    exit 1 when the block in the part differs from a fresh render (the drift guard in 89e / 96b)
//   --json <path>                               render another JSON file of the same shape ({generated, rows, overrides, retired_aliases})
//
// Rendered constants: PRICES_VERIFIED_ON (json.generated), DEFAULT_PRICES (rows → {pat,label,in,out,cw,cr,v,at,c,src}; the '.*' row is
// last), PRICE_OVERRIDES ({platform, …same}), MODEL_ALIASES ({'retired-id': 'successor-id'}, keys lowercased; entries without a successor
// are listed in a comment and fall to the Unknown-model row). The render is deterministic: same JSON → same bytes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeBuilt } from '../../tools/build.mjs';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
export const PART = path.join(ROOT, 'src', 'js', '02-prices.js');
const DEFAULT_JSON = path.join(ROOT, 'docs', 'superpowers', 'specs', '2026-10-15-price-rows.json');
export const BEGIN = '/* PRICES:BEGIN (generated by tests/tools/sync-prices.mjs — edit the JSON, not this block) */';
export const END = '/* PRICES:END */';

/** single-quoted JS string literal; null/undefined → null */
const q = (s) => s == null ? 'null' : "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r/g, '\\r').replace(/\n/g, '\\n') + "'";
const num = (v, what) => { if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`${what}: price is not a finite number (${JSON.stringify(v)})`); return String(v); };

function validate(json) {
  for (const k of ['generated', 'rows', 'overrides', 'retired_aliases']) if (!(k in json)) throw new Error(`JSON lacks "${k}"`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(json.generated)) throw new Error('generated must be YYYY-MM-DD');
  const all = json.rows.map((r, i) => [`rows[${i}]`, r]).concat(json.overrides.map((o, i) => [`overrides[${i}]`, o]));
  for (const [where, r] of all) {
    if (typeof r.pat !== 'string' || !r.pat) throw new Error(`${where}: empty pattern`);
    try { new RegExp(r.pat, 'i'); } catch (e) { throw new Error(`${where}: pattern does not compile: ${e.message}`); }
    if (typeof r.label !== 'string' || !r.label) throw new Error(`${where}: empty label`);
    for (const k of ['in', 'out', 'cw', 'cr']) num(r[k], `${where}.${k}`);
  }
  for (const [i, o] of json.overrides.entries()) if (typeof o.platform !== 'string' || !o.platform) throw new Error(`overrides[${i}]: missing platform`);
  const last = json.rows[json.rows.length - 1];
  if (!last || last.pat !== '.*') throw new Error("the last row must be the '.*' fallback");
  if (json.rows.filter(r => r.pat === '.*').length !== 1) throw new Error("exactly one '.*' row");
  const seen = new Set();
  for (const a of json.retired_aliases) {
    const k = String(a.id || '').toLowerCase();
    if (!k) throw new Error('alias with an empty id');
    if (seen.has(k)) throw new Error(`duplicate alias id ${k}`);
    seen.add(k);
  }
}

const rowLit = (r, extra) => `{ ${extra}pat: ${q(r.pat)}, label: ${q(r.label)}, in: ${num(r.in)}, out: ${num(r.out)}, cw: ${num(r.cw)}, cr: ${num(r.cr)}, v: ${q(r.vendor ?? r.platform ?? null)}, at: ${q(r.verified_on ?? null)}, c: ${q(r.confidence ?? null)}, src: ${q(r.source_url ?? null)} }`;

/** the block, as an array of lines (no line terminators) */
export function renderLines(json) {
  validate(json);
  const out = [BEGIN];
  out.push(`const PRICES_VERIFIED_ON = ${q(json.generated)};`);
  out.push('/* Row shape: pat = regex tried (case-insensitively) against the lowercased id AND normalizeModelId(id); first match wins, the \'.*\' row is last.');
  out.push(' * in/out/cw/cr = USD per 1M input / output / cache-write / cache-read tokens; v = vendor; at = date the price was verified (null = carried');
  out.push(' * over from the Aug 2026 list, unverified since); c = confidence (high / medium / low / existing); src = the vendor page the price was read from. */');
  out.push('const DEFAULT_PRICES = [');
  let vendor = null;
  for (const r of json.rows) {
    if (r.vendor !== vendor) { vendor = r.vendor; out.push(`  // --- ${vendor}`); }
    out.push(`  ${rowLit(r, '')},`);
  }
  out.push('];');
  out.push('/* Per-platform prices for ids a host bills differently from the vendor\'s default row — Pricing.resolve(model, platform) tries these');
  out.push(' * (platform must equal the row\'s platform string) before DEFAULT_PRICES. Constant: the price editor edits DEFAULT_PRICES rows only. */');
  out.push('const PRICE_OVERRIDES = [');
  for (const o of json.overrides) out.push(`  ${rowLit(o, `platform: ${q(o.platform)}, `)},`);
  out.push('];');
  out.push('/* Retired ids → the id the vendor now routes and bills them as. Pricing.resolve() prices the successor and sets aliasOf on the');
  out.push(' * returned object so the UI can say "priced as <successor>". Keys are lowercased; looked up for the raw id and its normalised form. */');
  out.push('const MODEL_ALIASES = {');
  const none = [];
  for (const a of json.retired_aliases) {
    if (!a.successor) { none.push(a.id); continue; }
    out.push(`  ${q(String(a.id).toLowerCase())}: ${q(a.successor)},`);
  }
  if (none.length) out.push(`  // no successor (shut down; fall to the Unknown-model row): ${none.join(', ')}`);
  out.push('};');
  out.push(END);
  return out;
}

/** locate the block (or, on the first run, the legacy DEFAULT_PRICES literal) in the part's text; returns [start, end) */
function locate(html) {
  const b = html.indexOf(BEGIN);
  if (b >= 0) {
    const e = html.indexOf(END, b);
    if (e < 0) throw new Error('PRICES:BEGIN without PRICES:END');
    return { start: b, end: e + END.length, fresh: false };
  }
  const s = html.indexOf('const DEFAULT_PRICES = [');
  if (s < 0) throw new Error('neither the PRICES markers nor "const DEFAULT_PRICES = [" found');
  const close = html.indexOf('\n];', s);
  if (close < 0) throw new Error('unterminated DEFAULT_PRICES literal');
  return { start: s, end: close + 3, fresh: true };
}

export function main(argv = process.argv.slice(2)) {
  const check = argv.includes('--check');
  const ji = argv.indexOf('--json');
  const jsonPath = ji >= 0 && argv[ji + 1] ? path.resolve(argv[ji + 1]) : DEFAULT_JSON;
  const json = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  const part = fs.readFileSync(PART, 'utf8');
  const eol = part.includes('\r\n') ? '\r\n' : '\n';
  const block = renderLines(json).join(eol);
  const { start, end, fresh } = locate(part);
  const current = part.slice(start, end);
  if (current === block) { console.log(`prices: in sync (${json.rows.length} rows, ${json.overrides.length} overrides, ${json.retired_aliases.filter(a => a.successor).length} aliases; verified ${json.generated})`); return 0; }
  if (check) {
    const a = current.split(eol), b = block.split(eol);
    let i = 0; while (i < a.length && i < b.length && a[i] === b[i]) i++;
    console.error(`prices: DRIFT — the block in ${path.relative(ROOT, PART)} differs from a fresh render of ${path.relative(ROOT, jsonPath)} (first difference at block line ${i + 1}${fresh ? '; markers missing' : ''}). Run: node tests/tools/sync-prices.mjs`);
    console.error('  part: ' + (a[i] ?? '<end>').slice(0, 160));
    console.error('  json: ' + (b[i] ?? '<end>').slice(0, 160));
    return 1;
  }
  const next = part.slice(0, start) + block + part.slice(end);
  if (/[\x00-\x08]/.test(next)) throw new Error('refusing to write: the render contains raw control bytes');
  fs.writeFileSync(PART, next);
  const builtBytes = writeBuilt();
  console.log(`prices: ${fresh ? 'created the PRICES block' : 'rewrote the PRICES block'} in ${path.relative(ROOT, PART)} — ${json.rows.length} rows, ${json.overrides.length} overrides, ${json.retired_aliases.filter(a => a.successor).length} aliases; verified ${json.generated}; ${Buffer.byteLength(next)} bytes; built AI Usage Dashboard.html (${builtBytes} bytes)`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exit(main()); } catch (e) { console.error('prices: ' + (e && e.message || e)); process.exit(2); }
}
